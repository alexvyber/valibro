"""Generate V Unicode 17.0 tables from a flattened UCD directory.
Usage: python3 tools/unicode/generate_tables.py UCD_DIRECTORY
Data license: unicode/LICENSE. Runtime tests use V only.
"""
from pathlib import Path
import sys
import shutil
import hashlib
import json
root = Path(sys.argv[1])
dest = Path(__file__).resolve().parents[2]
def read(name):return (root/name).read_text()
def rows(name):
 for line in read(name).splitlines():
  fields=line.split('#')[0].strip().split(';')
  if len(fields)>1:yield [f.strip() for f in fields]
def bounds(s):
 v=s.split('..');return int(v[0],16),int(v[-1],16)
def vstr(s):return "'"+s.replace('\\','\\\\').replace("'","\\'").replace('\n','\\n').replace('\r','\\r').replace('\t','\\t')+"'"
def code_str(s):return ''.join(chr(int(cp,16)) for cp in s.split())
ccc={};
decomp = {};
compat = {};
lower = {};
upper = {}; wordlike=[]
start=None
for f in rows('UnicodeData.txt'):
 cp = int(f[0], 16)
 cat = f[2]
 if f[1].endswith(', First>'):
  start = cp
 elif f[1].endswith(', Last>'):
  if cat[0] in 'LN': wordlike.append((start, cp, 1))
  start = None
 elif cat[0] in 'LN':
  wordlike.append((cp, cp, 1))
 if int(f[3]): ccc[cp] = int(f[3])
 if f[5]:
  seq = f[5].split()
  if seq[0].startswith('<'):
   compat[cp] = True
   seq = seq[1:]
  decomp[cp] = ''.join(chr(int(c, 16)) for c in seq)
 if f[12]: upper[cp] = chr(int(f[12], 16))
 if f[13]: lower[cp] = chr(int(f[13], 16))
for f in rows('SpecialCasing.txt'):
 if len(f) > 4 and not f[4]:
  cp = int(f[0], 16)
  lower[cp] = code_str(f[1])
  upper[cp] = code_str(f[3])
excluded=set()
for f in rows('DerivedNormalizationProps.txt'):
 if f[1]=='Full_Composition_Exclusion':
  a,b=bounds(f[0]);excluded.update(range(a,b+1))
compose={}
for cp,s in decomp.items():
 if cp not in compat and cp not in excluded and len(s)==2:
  compose[(ord(s[0])<<21)|ord(s[1])]=cp

def ranges(name,selector):
 result=[]
 for f in rows(name):
  val=selector(f)
  if val: a,b=bounds(f[0]);result.append((a,b,val))
 return sorted(result)
def merged(values):
 out=[]
 for a,b,c in sorted(values):
  if out and a==out[-1][1]+1 and c==out[-1][2]:out[-1]=(out[-1][0],b,c)
  else:out.append((a,b,c))
 return out
gb_names=['Other','CR','LF','Control','Extend','ZWJ','Regional_Indicator','Prepend','SpacingMark','L','V','T','LV','LVT']
wb_names=['Other','CR','LF','Newline','Extend','ZWJ','Regional_Indicator','Format','Katakana','Hebrew_Letter','ALetter','Single_Quote','Double_Quote','MidNumLet','MidLetter','MidNum','Numeric','ExtendNumLet','WSegSpace']
gb=ranges('auxiliary_GraphemeBreakProperty.txt',lambda f:gb_names.index(f[1]))
wb=ranges('auxiliary_WordBreakProperty.txt',lambda f:wb_names.index(f[1]))
incb=ranges('DerivedCoreProperties.txt',lambda f:['None','Consonant','Extend','Linker'].index(f[2]) if f[1]=='InCB' else 0)
cased=ranges('DerivedCoreProperties.txt',lambda f:1 if f[1]=='Cased' else 0)
ignorable=ranges('DerivedCoreProperties.txt',lambda f:1 if f[1]=='Case_Ignorable' else 0)
emoji={name:ranges('emoji_emoji-data.txt',lambda f:1 if f[1]==name else 0) for name in ['Emoji','Emoji_Presentation','Emoji_Modifier','Emoji_Modifier_Base','Extended_Pictographic']}
output='// Generated by tools/unicode/generate_tables.py from Unicode 17.0.0.\n// Unicode data license: LICENSE in this module directory.\nmodule unicode\n\npub const version = \'17.0.0\'\n\nstruct Range { start int end int value int }\n\n'
for name,data in [('canonical_class',ccc),('compatibility',compat),('decompositions',decomp),('lower_mappings',lower),('upper_mappings',upper),('compositions',compose)]:
 key='u64' if name=='compositions' else 'int';value='bool' if name=='compatibility' else 'string' if name in ['decompositions','lower_mappings','upper_mappings'] else 'int'
 output+=f'const {name} = {{\n'
 for k,v in sorted(data.items()):output+=f' {key}({k}): '+(vstr(v) if isinstance(v,str) else 'true' if v is True else str(v))+'\n'
 output+='}\n\n'
for name,data in [('grapheme_properties',gb),('word_properties',wb),('indic_properties',incb),('cased_properties',cased),('case_ignorable_properties',ignorable),('wordlike_properties',wordlike)]+[(name.lower()+'_properties',data) for name,data in emoji.items()]:
 output+=f'const {name} = [\n'
 for a,b,c in merged(data):output+=f' Range{{{a},{b},{c}}},\n'
 output+=']\n\n'
(dest/'unicode'/'tables_generated.v').write_text(output)
for name in ['NormalizationTest.txt','auxiliary_GraphemeBreakTest.txt','auxiliary_WordBreakTest.txt']:
 shutil.copyfile(root/name,dest/'tests'/'fixtures'/'unicode'/name)
manifest={f.name:hashlib.sha256(f.read_bytes()).hexdigest() for f in sorted(root.glob('*.txt'))}
(dest/'unicode'/'SOURCES.json').write_text(json.dumps({'unicode_version':'17.0.0','source_base':'https://www.unicode.org/Public/17.0.0/ucd/','sha256':manifest},indent=2)+'\n')
print(f'{len(decomp)} decompositions, {len(compose)} compositions; Unicode 17.0.0')
